package featurecat.lizzie.rules;

import featurecat.lizzie.analysis.GameInfo;
import featurecat.lizzie.enginegame.EngineGameRecord;
import featurecat.lizzie.enginegame.EngineGameRecordContext;
import java.util.ArrayDeque;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Objects;
import javax.swing.SwingUtilities;

/** Authored game state for continuations that must preserve edits while yielding the event thread. */
public final class GameEditSnapshot {
  private final Board board;
  private final BoardHistoryList history;
  private final BoardHistoryNode root;
  private final BoardHistoryNode cursor;
  private final long revision;
  private final int width;
  private final int height;
  private final GameMetadata metadata;
  private final BoardHistoryList.SessionRulesTarget rules;
  private final List<NodeState> nodes;

  private GameEditSnapshot(Board board) {
    this.board = Objects.requireNonNull(board, "board");
    history = Objects.requireNonNull(board.getHistory(), "history");
    revision = board.getContextRevision();
    width = Board.boardWidth;
    height = Board.boardHeight;
    List<NodeStructure> structure = new ArrayList<>();
    // Preserve the save pipeline's lock order: no BoardData lock while holding history.
    synchronized (history) {
      root = history.getStart();
      cursor = history.getCurrentHistoryNode();
      metadata = GameMetadata.capture(history.getGameInfo());
      rules = history.captureSessionRules();
      ArrayDeque<BoardHistoryNode> pending = new ArrayDeque<>();
      pending.add(root);
      while (!pending.isEmpty()) {
        BoardHistoryNode node = pending.removeFirst();
        List<BoardHistoryNode> children = List.copyOf(node.getVariations());
        structure.add(new NodeStructure(node, children));
        pending.addAll(children);
      }
    }
    List<NodeState> captured = new ArrayList<>(structure.size());
    for (NodeStructure node : structure) captured.add(NodeState.capture(node));
    nodes = List.copyOf(captured);
  }

  public static GameEditSnapshot capture(Board board) {
    requireEventThread();
    return new GameEditSnapshot(board);
  }

  public boolean isCurrent(Board currentBoard) {
    requireEventThread();
    if (currentBoard != board || board.getHistory() != history
        || board.getContextRevision() != revision) return false;
    GameEditSnapshot current = capture(board);
    return current.root == root && current.cursor == cursor && current.revision == revision
        && current.width == width && current.height == height
        && Objects.equals(current.metadata, metadata) && current.rules == rules
        && current.nodes.equals(nodes);
  }

  private static void requireEventThread() {
    if (!SwingUtilities.isEventDispatchThread()) {
      throw new IllegalStateException("Game edit snapshots belong to the event thread");
    }
  }

  private record GameMetadata(
      String black, String white, String date, double komi, int handicap, String result,
      EngineGameRecordContext engineContext, EngineGameRecord engineRecord) {
    static GameMetadata capture(GameInfo info) {
      if (info == null) return null;
      // engineGameSaveSnapshot is generated by saving, not an authored metadata change.
      return new GameMetadata(info.getPlayerBlack(), info.getPlayerWhite(), info.getDate(),
          info.getKomi(), info.getHandicap(), info.getResult(),
          info.engineGameRecordContext(), info.engineGameRecord());
    }
  }

  private record NodeStructure(BoardHistoryNode node, List<BoardHistoryNode> children) {}

  private record ExtraStone(int x, int y, boolean black) {}

  private record NodeState(
      BoardHistoryNode node, List<BoardHistoryNode> children,
      BoardNodeKind kind, List<Stone> stones, List<Integer> move,
      Stone color, boolean blackToPlay, boolean dummy, int moveNumber, int moveMNNumber,
      String comment, Map<String, String> properties, long analysisEditRevision,
      boolean removedStone, List<ExtraStone> extraStones) {
    static NodeState capture(NodeStructure structure) {
      BoardHistoryNode node = structure.node();
      BoardData data = node.getData();
      List<ExtraStone> extra = new ArrayList<>();
      synchronized (node) {
        if (node.extraStones != null) {
          for (ExtraStones stone : node.extraStones) {
            extra.add(new ExtraStone(stone.x, stone.y, stone.isBlack));
          }
        }
      }
      synchronized (data) {
        Map<String, String> properties = new LinkedHashMap<>(data.getProperties());
        // Normal engine adoption removes imported KGP; these properties describe analysis.
        properties.keySet().removeAll(List.of("KGP", "LZ", "LZ2", "LZOP", "LZOP2"));
        List<Integer> move = data.lastMove == null || data.lastMove.isEmpty() ? List.of()
            : Arrays.stream(data.lastMove.get()).boxed().toList();
        List<Stone> stones = data.stones == null ? null
            : Collections.unmodifiableList(Arrays.asList(data.stones.clone()));
        return new NodeState(node, structure.children(), data.getNodeKind(), stones, move,
            data.lastMoveColor, data.blackToPlay, data.dummy, data.moveNumber, data.moveMNNumber,
            data.authoredComment(), Collections.unmodifiableMap(properties), data.analysisEditRevision(),
            node.hasRemovedStone(), List.copyOf(extra));
      }
    }
  }
}
